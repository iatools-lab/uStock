import assert from 'node:assert/strict';
import { mkdtemp,rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright';
import readExcel from 'read-excel-file/node';
import { createProductionServer } from '../server/production.mjs';
import { agingStock, concentration, redistribution, riskMatrix } from '../src/domain/strategic-stock.js';

const folder=await mkdtemp(join(tmpdir(),'ukit-strategic-')),app=createProductionServer();let browser;
try{
  await new Promise(done=>app.server.listen(0,'127.0.0.1',done));
  const origin=`http://127.0.0.1:${app.server.address().port}`;
  browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const response=page.waitForResponse(r=>r.url().includes('/api/local-stock')&&r.status()===200,{timeout:90000});
  await page.goto(origin+'/directeur/analytique?startDate=2026-10-01&endDate=2026-10-31');
  const data=await(await response).json(),matrix=riskMatrix(data.analysis);
  await page.locator('[data-chart-type=heatmap] .apexcharts-canvas').waitFor({timeout:60000});
  assert.equal(await page.locator('.apexcharts-heatmap-rect').count(),matrix.zones.length*matrix.products.length);
  const riskPanel=page.locator('.risk-panel');
  await riskPanel.locator('.scope-help summary').click();
  const riskDownload=page.waitForEvent('download');
  await riskPanel.getByRole('button',{name:'Télécharger Excel : Où risque-t-on de manquer de kits ?',exact:true}).click();
  const download=await riskDownload,path=join(folder,'risques.xlsx');await download.saveAs(path);
  const sheets=await readExcel(path);assert.equal(sheets[0].data.length,matrix.positions.length+1);
  assert.equal(sheets[0].data.slice(1).reduce((n,r)=>n+r[3],0),matrix.positions.reduce((n,r)=>n+r.stock,0));
  await page.getByRole('button',{name:'Agrandir : Où risque-t-on de manquer de kits ?',exact:true}).click();
  await page.locator('.chart-detail-dialog [data-chart-type=heatmap] .apexcharts-canvas').waitFor();
  await page.keyboard.press('Escape');
  console.log('Matrice, données complètes et export Excel : OK.');
  await page.getByRole('tab',{name:'Kit',exact:true}).click();
  const pareto=page.locator('.strategy-section .apex-chart');await pareto.locator('.apexcharts-canvas').waitFor();
  assert.equal(concentration(data.analysis,'zone').reduce((n,r)=>n+r.quantity,0),Number(data.metrics.deployed.value));
  await page.getByRole('button',{name:'Produits',exact:true}).click();
  await pareto.locator('.apexcharts-canvas').waitFor();
  assert.equal(concentration(data.analysis,'product').at(-1).cumulative,100);
  await page.getByRole('tab',{name:'État',exact:true}).click();
  await page.getByRole('heading',{name:'Ancienneté du stock par zone',exact:true}).waitFor();
  const age=agingStock(data.analysis);assert.equal(age.rows.reduce((n,r)=>n+r.quantity,0),matrix.positions.reduce((n,r)=>n+r.stock,0));
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.getByRole('tab',{name:'État',exact:true}).isVisible());
  const forecastResponse=page.waitForResponse(r=>r.url().includes('view=forecast')&&r.status()===200,{timeout:90000});
  await page.goto(origin+'/directeur/previsions?startDate=2026-10-01&endDate=2026-10-31');
  const forecast=await(await forecastResponse).json(),plans=redistribution(forecast.analysis);
  await page.getByRole('heading',{name:'Propositions de redistribution',exact:true}).waitFor();
  const table=page.locator('section').filter({has:page.getByRole('heading',{name:'Propositions de redistribution',exact:true})}).last();
  assert.equal(await table.locator('tbody tr').count(),plans.plans.length);
  await page.getByRole('tab',{name:'Par area manager',exact:true}).click();
  assert.equal(await page.getByRole('heading',{name:'Propositions de redistribution',exact:true}).count(),0);
  assert.deepEqual(errors,[]);
  console.log('Concentration, ancienneté, redistribution par référence et mobile : OK.');
}finally{await browser?.close();await app.close();await rm(folder,{recursive:true,force:true});}
