import assert from 'node:assert/strict';
import { mkdtemp,rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright';
import readExcel from 'read-excel-file/node';
import { createLocalDatabase } from '../server/local-database.mjs';
import { productionSelection } from '../server/production-selection.mjs';
import { createProductionServer } from '../server/production.mjs';
const store=productionSelection(':memory:'),database=createLocalDatabase({selectionStore:store});
const app=createProductionServer({database}),folder=await mkdtemp(join(tmpdir(),'ustock-sales-'));let browser;
try{
 await new Promise(done=>app.server.listen(0,'127.0.0.1',done));
 const base=`http://127.0.0.1:${app.server.address().port}`,period='?startDate=2026-10-01&endDate=2026-10-31';
 browser=await chromium.launch({channel:'chrome',headless:true});const context=await browser.newContext({acceptDownloads:true});
 const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
 const loaded=page.waitForResponse(r=>r.url().includes('/api/local-stock?')&&r.status()===200,{timeout:180000});
 await page.goto(base+'/directeur'+period);const before=await(await loaded).json();
 await page.locator('.overview-metric').last().waitFor();
 async function download(button,name){const wait=page.waitForEvent('download',{timeout:180000});await button.click();const item=await wait;const path=join(folder,name+'.xlsx');await item.saveAs(path);return (await readExcel(path))[0].data;}
 const initial=await download(page.getByRole('button',{name:'Télécharger Excel : Identifiants des ventes',exact:true}),'avant');
 assert.equal(initial.length-1,Number(before.metrics.deployed.value));
 assert.equal(new Set(initial.slice(1).map(r=>r[1])).size,initial.length-1);
 const targetReference=initial.slice(1).find(r=>r[0]&&r[2])?.[2];assert.ok(targetReference);
 const target=initial.slice(1).filter(r=>r[2]===targetReference);assert.ok(target.length>0);
 await database.saveSelection({kind:'asset',keys:[target[0][0]],included:true});
 const admin=await context.newPage();admin.on('pageerror',e=>errors.push(e.message));
 await admin.goto(base+'/admin');await admin.getByRole('button',{name:'Par produit',exact:true}).waitFor({timeout:180000});
 await admin.getByRole('button',{name:'Par produit',exact:true}).click();
 await admin.getByLabel('Rechercher un produit',{exact:true}).fill(targetReference);
 await admin.getByRole('checkbox',{name:`Sélectionner le produit ${targetReference}`,exact:true}).check();
 const saved=admin.waitForResponse(r=>r.url().includes('/api/analysis-selection')&&r.request().method()==='POST'&&r.status()===200,{timeout:180000});
 await admin.getByRole('button',{name:'Exclure la sélection',exact:true}).click();const revision=(await(await saved).json()).revision;
 await page.bringToFront();
 const expected=initial.length-1-target.length;
 await page.waitForFunction(n=>Number(document.querySelectorAll('.overview-metric strong')[2]?.textContent.replace(/\D/g,''))===n,expected,{timeout:180000});
 const after=await download(page.getByRole('button',{name:'Télécharger Excel : Identifiants des ventes',exact:true}),'apres');
 assert.equal(after.length-1,expected);assert.ok(after.slice(1).every(r=>r[2]!==targetReference));
 const stale=await page.request.get(base+'/api/sales-export'+period+'&revision='+before.selection.revision+'&expectedCount='+before.metrics.deployed.value);assert.equal(stale.status(),409);
 const audit=await database.administration(new URLSearchParams({product:targetReference}));assert.ok(audit.rows.length>0&&audit.rows.every(r=>!r.included));
 assert.ok(audit.options.products.some(r=>r.value===targetReference));
 const stockLoaded=page.waitForResponse(r=>r.url().includes('view=stock')&&r.status()===200,{timeout:180000});
 await page.getByRole('link',{name:'Stock national',exact:true}).click();const stock=await(await stockLoaded).json();
 const place=stock.territories.rows.find(r=>Number(r.deployed)>0);assert.ok(place);
 const sold=stock.territories.rows.filter(r=>r.key===place.key).reduce((n,r)=>n+Number(r.deployed),0);
 const placeFile=await download(page.getByRole('button',{name:`Télécharger Excel : Ventes - ${place.label}`,exact:true}),'lieu');assert.equal(placeFile.length-1,sold);
 assert.equal(await page.getByRole('dialog').count(),0);
 const placeButton=page.getByRole('button',{name:`Télécharger Excel : Ventes - ${place.label}`,exact:true});
 await placeButton.locator('xpath=ancestor::article[1]').locator('.territory-mix-button').click();
 const dialog=page.getByRole('dialog');await dialog.waitFor();
 const summary=await download(dialog.getByRole('button',{name:`Télécharger Excel : Ventes — ${place.label}`,exact:true}),'mix');assert.equal(summary.length-1,sold);
 let productRow;
 for(const row of await dialog.locator('.product-state-table tbody tr').all())if(Number((await row.locator('td').nth(2).innerText()).replace(/\D/g,''))>0){productRow=row;break;}
 assert.ok(productRow);const productCount=Number((await productRow.locator('td').nth(2).innerText()).replace(/\D/g,''));
 const productFile=await download(productRow.getByRole('button',{name:/Télécharger Excel/}),'produit');assert.equal(productFile.length-1,productCount);
 const placeContracts=new Set(placeFile.slice(1).map(r=>r[1]));assert.ok(productFile.slice(1).every(r=>placeContracts.has(r[1])));
 await dialog.getByRole('button',{name:'Fermer le mix produit',exact:true}).click();
 const compared=page.waitForResponse(r=>r.url().includes('view=performance')&&r.status()===200,{timeout:180000});
 await page.getByRole('link',{name:'Comparaison des performances',exact:true}).click();const comparison=await(await compared).json();
 const reference=await download(page.getByRole('button',{name:'Télécharger Excel : Identifiants des ventes de référence',exact:true}),'reference');
 assert.equal(reference.length-1,comparison.analysis.previous.rows.reduce((n,r)=>n+r.quantity,0));
 assert.ok(reference.slice(1).every(r=>r[6]?.startsWith('2026-09-')));
 assert.equal(store.read().revision,revision);assert.deepEqual(errors,[]);
 console.log(`Administration et Excel : ${initial.length-1} ventes avant, ${expected} apres exclusion ; exports lieu, mix, produit et reference conformes. Aucune ecriture dans Upya.`);
}finally{await browser?.close();await app.close();await rm(folder,{recursive:true,force:true});}
